    private void ubaciFldDatum() {
        try {
            MaskFormatter mskf1 = new MaskFormatter("##.##.####.");
            mskf1.setPlaceholderCharacter('_');
            txtDatum.setFormatterFactory(new DefaultFormatterFactory(mskf1));
            MaskFormatter mskf2 = new MaskFormatter("##:##");
            mskf2.setPlaceholderCharacter('_');
            txtVreme.setFormatterFactory(new DefaultFormatterFactory(mskf2));
        } catch (ParseException ex) {
            ex.printStackTrace();
        }
        
    }

    private void fillCmb() {
        try{
            Controller controller = new Controller();
            List<Pacijent> pacijenti = controller.vratiListuPacijent();
            DefaultComboBoxModel cmbModelPacijenti = new DefaultComboBoxModel();
            cmbModelPacijenti.addAll(pacijenti);
            
            cmbPacijenti.setModel(cmbModelPacijenti);
            
            
        }catch(Exception ex){
            JOptionPane.showMessageDialog(this, ex, "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }

